import { readdir, readFile, writeFile } from 'node:fs/promises'
import { resolve, relative, sep } from 'node:path'
import { format } from 'prettier'

const repositoryRoot = resolve(import.meta.dirname, '..')
const pluginRoot = resolve(repositoryRoot, 'packages/agent/plugin/programkit')
const outputPath = resolve(repositoryRoot, 'apps/cloudflare/src/agent-plugin-source.generated.ts')

async function filesBelow(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = await Promise.all(
    entries.map((entry) => {
      const path = resolve(directory, entry.name)
      return entry.isDirectory() ? filesBelow(path) : [path]
    }),
  )
  return files.flat().sort()
}

function moduleString(value) {
  return JSON.stringify(value).replaceAll('\u2028', '\\u2028').replaceAll('\u2029', '\\u2029')
}

const portableManifestSource = await readFile(resolve(pluginRoot, 'plugin.json'), 'utf8')
const codexManifestSource = await readFile(resolve(pluginRoot, '.codex-plugin/plugin.json'), 'utf8')
const sourceFiles = [
  ...(await filesBelow(resolve(pluginRoot, 'assets'))),
  ...(await filesBelow(resolve(pluginRoot, 'skills'))),
]
const sharedEntries = await Promise.all(
  sourceFiles.map(async (path) => [
    relative(pluginRoot, path).split(sep).join('/'),
    await readFile(path, 'utf8'),
  ]),
)

const source = await format(
  `// Generated by scripts/generate-agent-plugin-source.mjs. Do not edit by hand.\n\nexport const portableManifestSource = ${moduleString(portableManifestSource)}\n\nexport const codexManifestSource = ${moduleString(codexManifestSource)}\n\nexport const sharedPluginSources: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(sharedEntries), null, 2)}\n`,
  {
    parser: 'typescript',
    printWidth: 100,
    semi: false,
    singleQuote: true,
    trailingComma: 'all',
  },
)

if (process.argv.includes('--check')) {
  let existing = ''
  try {
    existing = await readFile(outputPath, 'utf8')
  } catch {
    // The actionable error below is clearer than the raw filesystem error.
  }
  if (existing !== source) {
    throw new Error(
      'The generated agent plugin source is stale. Run pnpm agent-plugin-source:generate.',
    )
  }
} else {
  await writeFile(outputPath, source, 'utf8')
}
